// Disposable Mongo Unix socket only; never reads .env or contacts providers/MCP.
const assert = require('node:assert/strict');
require('module-alias').addAlias('~', '/app/api');
const mongoose = require('mongoose');
const schemas = require('@librechat/data-schemas');
schemas.logger.silent = true;
schemas.createModels(mongoose);
const db = require('~/models');
const api = require('@librechat/api');
const native = require('librechat-data-provider');
const { createAdapter } = require('/app/kai-platform/setup_agents.cjs');
const { provisionManagedAgents } = require('/app/kai-platform/managed_agent_setup.cjs');
(async () => {
  await mongoose.connect('mongodb://%2Fsocket%2Fmongodb-27017.sock', { dbName: 'setup_fixture', serverSelectionTimeoutMS: 5000 });
  await db.seedDatabase();
  const owner = await mongoose.model('User').create({ role: 'ADMIN', name: 'Fixture', email: 'setup@example.invalid', provider: 'local', emailVerified: true });
  const baseline = { modelSpecs: { list: [{ name: 'kai-assistant', label: 'Fixture', preset: { endpoint: 'openAI', model: 'fixture' } }] }, mcpConfig: { clickhouse: { type: 'streamable-http', url: 'http://invalid.invalid/mcp' } } };
  const store = new Map();
  const service = api.createAppConfigService({ loadBaseConfig: async () => baseline, setCachedTools: async () => {}, getCache: () => ({ get: async key => store.get(key), set: async (key, value) => store.set(key, value), delete: async key => store.delete(key) }), cacheKeys: { APP_CONFIG: 'fixture' }, getApplicableConfigs: db.getApplicableConfigs, getUserPrincipals: db.getUserPrincipals });
  const configService = { getAppConfig: service.getAppConfig, invalidateConfigCaches: async () => { store.clear(); } };
  let writes = 0;
  const deps = createAdapter({ db, mongoose, permissions: require('~/server/services/PermissionService'), capabilities: require('~/server/middleware/roles/capabilities'), configService, api, native, nanoid: require('nanoid').nanoid, brand: 'Fixture', beforeWrite: async () => { writes++; } });
  const first = await provisionManagedAgents(String(owner._id), deps);
  assert.deepEqual(first.general.tools, ['file_search']);
  assert.equal(first.warehouse.tools.length, 10);
  assert.ok((await db.getAgentVersions({ id: first.general.id })).length);
  const before = writes;
  const second = await provisionManagedAgents(String(owner._id), deps);
  assert.equal(second.general.id, first.general.id);
  assert.equal(second.warehouse.id, first.warehouse.id);
  assert.equal(writes, before);
  const rolePrincipals = [{ principalType: native.PrincipalType.ROLE, principalId: 'USER' }];
  assert.equal((await db.findEntriesByPrincipalsAndResource(rolePrincipals, native.ResourceType.AGENT, first.warehouse._id)).length, 0);
  assert.equal((await db.findEntriesByPrincipalsAndResource(rolePrincipals, native.ResourceType.AGENT, first.general._id)).length, 1);
  await require('~/server/services/PermissionService').grantPermission({ principalType: native.PrincipalType.ROLE, principalId: 'USER', resourceType: native.ResourceType.AGENT, resourceId: first.warehouse._id, accessRoleId: native.AccessRoleIds.AGENT_VIEWER, grantedBy: String(owner._id) });
  const beforeReject = writes;
  await assert.rejects(provisionManagedAgents(String(owner._id), deps));
  assert.equal(writes, beforeReject);
  const { createAccounts } = require('/app/kai-platform/accounts.cjs');
  const accounts = createAccounts({ mongoose, hasCapability: async () => true, origin: 'https://fixture.invalid' });
  const target = await mongoose.model('User').create({ role: 'USER', name: 'Disable fixture', email: 'disable@example.invalid', provider: 'local', emailVerified: true });
  const targetId = String(target._id);
  await mongoose.model('Session').collection.insertMany([{ user: target._id, expiration: new Date(Date.now() + 60000), refreshTokenHash: 'fixture-one' }, { user: targetId, expiration: new Date(Date.now() + 60000), refreshTokenHash: 'fixture-two' }]);
  await accounts.assertCanAuthenticate(targetId);
  const disabled = await accounts.disable({ user: { id: String(owner._id) }, params: { id: targetId }, body: {} });
  assert.equal(disabled.account.status, 'disabled');
  assert.equal(disabled.account.warehouse_revocation_pending, true);
  const request={user:{id:String(owner._id)},params:{id:targetId},body:{}};
  assert.equal((await accounts.warehouseRevocationContext(request)).status,'disabled');
  await assert.rejects(accounts.warehouseContext(request,true),{status:403});
  assert.equal((await accounts.completeWarehouseRevocation(request)).warehouse_revocation_pending,false);
  assert.equal(disabled.cleanup_complete, true);
  assert.equal(await mongoose.model('Session').collection.countDocuments({ user: { $in: [target._id, targetId] } }), 0);
  await assert.rejects(accounts.assertCanAuthenticate(targetId), { status: 403, code: 'ACCOUNT_INACTIVE' });
  let responseCode, passed = false;
  await accounts.gate({ user: { id: targetId } }, { status(code) { responseCode = code; return this; }, json(body) { assert.equal(body.code, 'ACCOUNT_DISABLED'); } }, () => { passed = true; });
  assert.equal(responseCode, 403); assert.equal(passed, false);
  let issued = false;
  await assert.rejects(accounts.issueTokens(targetId, {}, async () => { issued = true; }), { code: 'ACCOUNT_INACTIVE' });
  assert.equal(issued, false);
  console.log('Native setup Mongo: schema/version creation, owner ACLs, General role views, private CH, idempotent base config, native disable/session wipe/JWT and token guard passed.');
})().then(async () => { await mongoose.disconnect(); process.exit(0); }).catch(async error => { console.error('Native setup fixture failed.', error.stack); await mongoose.disconnect(); process.exit(1); });
